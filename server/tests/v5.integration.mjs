import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const require=createRequire(import.meta.url);
test('V5 paid extensions, slot conflicts, deadlines and safe activation',()=>{
 const dir=mkdtempSync(join(tmpdir(),'fr-v5-'));
 process.env.DB_PATH=join(dir,'data.db');process.env.V3_PREVIEW='false';process.env.SANDBOX_MODE='true';
 const orders=require('../dist/lib/testOrders.js'),v5=require('../dist/lib/v5Bookings.js'),{db}=require('../dist/db.js');
 const features=require('../dist/lib/v3Features.js');
 const add=(id)=>db.prepare('INSERT INTO accounts(id,name,email,password,created_at) VALUES (?,?,?,?,?)').run(id,id,`${id}@example.invalid`,'private-password',new Date().toISOString());
 const paid=(o)=>orders.claimPayment(o.id,o.chat_id);
 try{
  add('a');add('b');add('c');
  assert.equal(orders.PRICES[0.5],70);
  const half=orders.createWebOrder('Half Customer','',0.5,'123').order;paid(half);orders.approveOrder(half.id,'a');orders.markDelivered(half.id);
  assert.equal(v5.extensionEligibility(orders.getOrder(half.id)).allowed,false);
  assert.throws(()=>v5.createExtensionOrder(orders.getOrder(half.id)),/30-minute/);
  assert.throws(()=>features.extendBooking(half.id),/30-minute/);
  assert.throws(()=>orders.createManualExtension('Half Customer','',50,'a'),/30-minute/);
  const full=orders.createWebOrder('Full Customer','',1,'456').order;paid(full);orders.approveOrder(full.id,'b');orders.markDelivered(full.id);
  const before=orders.getOrder(full.id).expires_at;
  const extension=v5.createExtensionOrder(orders.getOrder(full.id)).order;
  assert.equal(v5.createExtensionOrder(orders.getOrder(full.id)).order.id,extension.id);
  assert.equal(orders.getOrder(full.id).expires_at,before);
  assert.throws(()=>v5.confirmSlotPayment(extension.id),/not been verified/);
  paid(extension);assert.equal(v5.confirmSlotPayment(extension.id),'extension');
  const after=orders.getOrder(full.id).expires_at;
  assert.equal(Date.parse(after)-Date.parse(before),3600000);
  assert.equal(db.prepare('SELECT run_at FROM auto_reset_schedule WHERE account_id=?').get('b').run_at,after);
  assert.equal(orders.getOrder(extension.id).amount,50);
  assert.equal(orders.getOrder(extension.id).status,'delivered');
  v5.confirmSlotPayment(extension.id);assert.equal(orders.getOrder(full.id).expires_at,after);
  const next=v5.availability(1).find(a=>a.id==='b').availableAt;
  const reserved=v5.createAdvanceOrder('Next Customer','789',1,'b',next).order;
  assert.throws(()=>v5.createAdvanceOrder('Duplicate Customer','987',1,'b',next),/changed|overlap/);
  assert.equal(v5.extensionEligibility(orders.getOrder(full.id)).allowed,false);
  paid(reserved);v5.confirmSlotPayment(reserved.id);
  assert.equal(orders.getOrder(reserved.id).status,'reserved');
  assert.equal(orders.publicWebOrder(reserved.id,reserved.access_token).credentials,null);
  assert.throws(()=>features.extendBooking(full.id),/overlap/);
  assert.equal(v5.activateReservations().length,0);
  const timed=orders.createWebOrder('Late Customer','',1,'321').order;paid(timed);orders.approveOrder(timed.id,'c');orders.markDelivered(timed.id);
  const original=orders.getOrder(timed.id).expires_at;
  const late=v5.createExtensionOrder(orders.getOrder(timed.id)).order;
  db.prepare('UPDATE booking_slots SET hold_until=? WHERE order_id=?').run(new Date(Date.now()-1).toISOString(),late.id);
  paid(late);v5.confirmSlotPayment(late.id);
  assert.equal(orders.getOrder(late.id).status,'payment_late');
  assert.equal(orders.getOrder(timed.id).expires_at,original);
  assert.equal(db.prepare('SELECT run_at FROM auto_reset_schedule WHERE account_id=?').get('c').run_at,original);
  db.prepare('UPDATE booking_slots SET starts_at=?,ends_at=? WHERE order_id=?').run(new Date(Date.now()-1000).toISOString(),new Date(Date.now()+3600000).toISOString(),reserved.id);
  assert.equal(v5.activateReservations().length,0);
  orders.markReset('b',true);db.prepare("UPDATE auto_reset_schedule SET status='done' WHERE account_id='b'").run();
  assert.equal(v5.activateReservations().length,1);
  assert.equal(orders.getOrder(reserved.id).status,'delivered');
  assert.equal(v5.activateReservations().length,0);
  assert.equal(orders.publicWebOrder(reserved.id,reserved.access_token).credentials.email,'b@example.invalid');
  assert.throws(()=>orders.publicWebOrder(reserved.id,'another-customers-token'),/not found/);
  assert.equal(orders.summary().revenue,470);
 }finally{db.close();rmSync(dir,{recursive:true,force:true});}
});
